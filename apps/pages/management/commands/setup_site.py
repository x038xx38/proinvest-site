    def course_body(self):
        """Тело страницы курса с фото автора (загружается в библиотеку изображений один раз)."""
        photo = Image.objects.filter(title=AUTHOR_NAME).first()
        if not photo:
            with AUTHOR_PHOTO.open("rb") as f:
                photo = Image(title=AUTHOR_NAME, file=ImageFile(f, name="author.jpg"))
                photo.save()
        body = copy.deepcopy(COURSE_BODY)
        for block in body:
            if block["type"] == "person":
                block["value"]["photo"] = photo.pk
        return body

    def link_legal_pages(self, privacy, consent):
        """Ссылки на документы в формах и подвале — только если их ещё не настроили в CMS."""
        settings = SiteSettings.load()
        if not settings.privacy_page_id or not settings.consent_page_id:
            settings.privacy_page = settings.privacy_page or privacy
            settings.consent_page = settings.consent_page or consent
            settings.save()
            self.log("Настройки сайта: юридические документы")

        nav = Navigation.load()
        links = list(nav.legal_links.raw_data)
        if not any(item["value"].get("url") == consent.url for item in links):
            nav.legal_links = [
                *links,
                {"type": "link", "value": link("Согласие на обработку данных", consent.url)},
            ]
            nav.save()
            self.log("Навигация: ссылка на согласие в подвале")

    def child(self, parent, model, slug, **fields):
        existing = parent.get_children().filter(slug=slug).first()
        if existing:
            return existing.specific
        page = model(slug=slug, **fields)
        parent.add_child(instance=page)
        page.save_revision().publish()
        self.log(f"{page.url}: {page.title}")
        return page

    def log(self, message):
        self.stdout.write(f"  + {message}")
